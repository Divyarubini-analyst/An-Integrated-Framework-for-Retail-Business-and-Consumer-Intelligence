-- task 3 Join orders, order_items, and products to display detailed line items-
use bicycle_retail;

select od.Customer_ID,op.quantity,op.Discount,op.List_Price,pd.Product_Name,pd.Product_ID,pd.Category_ID 
from bicycle_retail.order_items as op
inner join bicycle_retail.orders as od
on od.Order_ID = op.Order_ID
inner join bicycle_retail.product as pd
on pd.Product_ID = op.Product_ID;



-- task 4  Write a query to group sales (total_price) by each store_id
select o.store_ID ,sum(op.total_price) from bicycle_retail.order_items as op
left join orders as o
on o.order_ID=op.Order_ID
group by o.store_ID
order by sum(total_price) desc;

-- Task 5 Use ORDER BY and LIMIT to get the top 5 most sold products by quantity.--
 
select op.Product_ID,p.product_name,sum(op.quantity)*op.list_price  as top_sold_product
from bicycle_retail.product as p
right join bicycle_retail.order_items as op
on op.Product_ID =p.product_id 
group by op.product_ID,p.Product_Name,op.list_price
order by top_sold_product desc limit 5;

